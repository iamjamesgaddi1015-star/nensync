// Generated from the reviewed migration in an ephemeral PostgreSQL instance.
// Never connects to a hosted database or reads environment/credential files.
import { writeFile, mkdir } from "node:fs/promises";
import { createDatabase } from "../tests/db-fixture";

const db = await createDatabase();
type Column = {
  table_name: string;
  column_name: string;
  data_type: string;
  is_nullable: string;
  column_default: string | null;
};
const { rows } = await db.query<Column>(
  `select table_name,column_name,data_type,is_nullable,column_default from information_schema.columns where table_schema = 'public' order by table_name,ordinal_position`,
);
const type = (c: Column) =>
  `${["integer", "smallint", "bigint", "numeric"].includes(c.data_type) ? "number" : c.data_type === "boolean" ? "boolean" : "string"}${c.is_nullable === "YES" ? " | null" : ""}`;
const tables = [...new Set(rows.map((c) => c.table_name))]
  .map((name) => {
    const cols = rows.filter((c) => c.table_name === name);
    const fields = (mode: "Row" | "Insert" | "Update") =>
      cols
        .map(
          (c) =>
            `${c.column_name}${mode === "Update" || (mode === "Insert" && (c.column_default !== null || c.is_nullable === "YES")) ? "?" : ""}: ${type(c)};`,
        )
        .join("\n");
    return `${name}: { Row: { ${fields("Row")} }; Insert: { ${fields("Insert")} }; Update: { ${fields("Update")} }; Relationships: [] };`;
  })
  .join("\n");
const output = `// Generated by npm run db:types from the NenSync migration. Do not edit by hand.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];
export type Database = { public: {
  Tables: { ${tables} };
  Views: { [_ in never]: never };
  Functions: {
    workspace_snapshot: { Args: Record<PropertyKey, never>; Returns: Json };
    save_standup: { Args: { p_day: string; p_version: number; p_yesterday: string; p_today: string; p_blockers: string }; Returns: Json };
    mutate_task: { Args: { p_action: string; p_id: string; p_version: number; p_title: string; p_tag: string }; Returns: Json };
    control_timer: { Args: { p_action: string; p_version: number; p_interval_id: string | null; p_seconds: number; p_task_id: string | null }; Returns: Json };
    update_profile: { Args: { p_name: string; p_timezone: string; p_version: number }; Returns: Json };
  };
  Enums: { [_ in never]: never }; CompositeTypes: { [_ in never]: never };
} };
export type Tables<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Row'];
`;
await mkdir("src/lib/supabase", { recursive: true });
await writeFile("src/lib/supabase/database.types.ts", output);
await db.close();
console.log(
  "Generated public database types from ephemeral migration catalog.",
);
